#!/usr/bin/env bash
# The terminal sessions quoted in lesson 2 of llm-observability, as a script
# that produces them.
#
# THE SCRIPT IS THE SOURCE AND ITS OUTPUT IS NOT COMMITTED. Every transcript in
# this lesson was copied from running it.
#
#   sudo bash ../../lab.sh up        # once
#   sudo bash captures.sh
#
# What is STAGED rather than typed, and not shown in the lesson: the lab
# (lab.sh reset), and copying the course's programs into ~/obs from
# ../../lab/code (telemetry.py, redact.py, assistant.py, replay.py, tree.py).
# The programs this lesson writes are put below and shown in it in full.
#
# WHAT THE CUSTOMERS TYPED WAS WRITTEN BY THE COURSE: data/traffic.jsonl is
# generated by ../../lab/traffic.py, and every name, address, telephone number
# and order number in it is invented, under domains reserved for examples.
# Replies come from extract-1, the lab's stand-in model (rag's lab/labgen.py).
#
# presidio_try.py turns warnings off: on every run, tldextract (which
# Presidio's URL recogniser uses) tries to download the public suffix list,
# cannot, and falls back to the copy it ships with, printing a traceback that
# has nothing to do with the lesson. Presidio's scores are its own and are
# printed as it returned them.
#
# Recorded on Ubuntu 24.04, Python 3.11, TZ=America/Sao_Paulo, on 2026-10-06.
set -uo pipefail
export TZ=America/Sao_Paulo LC_ALL=C.UTF-8
cd "$(dirname "$0")"
LAB_SH=${LAB_SH:-../../lab.sh}
CODE=$(cd "$(dirname "$LAB_SH")" && pwd)/lab/code
lab() { bash "$LAB_SH" "$@"; }
on() { printf 'ana@lab:~/obs$ %s\n' "$*"; lab exec "$*" 2>&1 || true; }
put() { lab exec "mkdir -p \"\$(dirname '$1')\" && cat > '$1'"; }
use() { for f in "$@"; do put "$f" < "$CODE/$f"; done; }
block() { printf '##### %s\n' "$1"; }
exec 9>/var/tmp/llmobs-capture.lock; flock 9
lab reset >/dev/null
use telemetry.py redact.py assistant.py replay.py tree.py
lab exec 'python assistant.py "warm up" >/dev/null; rm -f spans.jsonl'

