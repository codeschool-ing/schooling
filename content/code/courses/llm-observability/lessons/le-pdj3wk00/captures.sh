put leak.py <<'PY'
"""leak.py: one customer message through an instrumented SDK, with and without a redacting exporter."""
import sys

from openai import OpenAI
from openinference.instrumentation.openai import OpenAIInstrumentor
from opentelemetry.sdk.trace import ReadableSpan, TracerProvider
from opentelemetry.sdk.trace.export import SimpleSpanProcessor, SpanExporter

import redact
import telemetry


class Redacting(SpanExporter):
    """Hands every span on to INNER with each string attribute, and each event's, passed through redact()."""

    def __init__(self, inner):
        self.inner = inner

    def export(self, spans):
        clean = lambda attrs: {k: redact.redact(v) if isinstance(v, str) else v for k, v in attrs.items()}
        return self.inner.export([ReadableSpan(
            name=s.name, context=s.context, parent=s.parent, resource=s.resource,
            attributes=clean(s.attributes), links=s.links, kind=s.kind, status=s.status,
            events=[type(e)(e.name, clean(e.attributes), e.timestamp) for e in s.events],
            start_time=s.start_time, end_time=s.end_time, instrumentation_scope=s.instrumentation_scope)
            for s in spans])

    def shutdown(self):
        self.inner.shutdown()


out = sys.argv[1]
exporter = telemetry.JsonlExporter(out)
if "--redact" in sys.argv:
    exporter = Redacting(exporter)
provider = TracerProvider()
provider.add_span_processor(SimpleSpanProcessor(exporter))
OpenAIInstrumentor().instrument(tracer_provider=provider)
OpenAI().chat.completions.create(model="extract-1", messages=[{"role": "user", "content":
    "Hi, I'm Joana Prado (joana.prado@example.com, +55 11 5550-0142). Is my order MG-20481937 lost?"}])
