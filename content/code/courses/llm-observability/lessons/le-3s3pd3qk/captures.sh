#!/usr/bin/env bash
# The terminal sessions quoted in lesson 3 of llm-observability, as a script
# that produces them.
#
# THE SCRIPT IS THE SOURCE AND ITS OUTPUT IS NOT COMMITTED. Every transcript in
# this lesson was copied from running it.
#
#   sudo bash ../../lab.sh up        # once
#   sudo bash captures.sh
#
# What is STAGED rather than typed, and not shown in the lesson: the lab
# (lab.sh reset), and copying the course's programs into ~/obs from
# ../../lab/code. replay.py and costs.py are shown in the lesson; the others
# are lesson 1's and 2's. The programs this lesson writes are put below and
# shown in full.
#
# THE WEEK IS SIMULATED. The requests are data/traffic.jsonl, generated by
# ../../lab/traffic.py; what the simulated customers do after a reply is
# decided by rules written in replay.py. Every reply comes from extract-1, the
# lab's stand-in model, and THE PRICES IN prices.json WERE WRITTEN BY THE
# COURSE: no provider charges them. Token counts are labobs' usage figures.
# What is computed here, every count, sum and share, is real arithmetic on
# those.
#
# Recorded on Ubuntu 24.04, Python 3.11, TZ=America/Sao_Paulo, on 2026-10-06.
set -uo pipefail
export TZ=America/Sao_Paulo LC_ALL=C.UTF-8
cd "$(dirname "$0")"
