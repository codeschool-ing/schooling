#!/usr/bin/env bash
# The terminal sessions quoted in lesson 15 of python-back, as a script that
# produces them.
#
# THE SCRIPT IS THE SOURCE AND ITS OUTPUT IS NOT COMMITTED. Every transcript in
# this lesson was copied from running it:
#
#   sudo bash captures.sh
#
# What is STAGED rather than typed: the machine lesson 14 left (`lab.sh reset
# 15`). Every file the lesson shows whole is taken from its section by `from`.
# The edits a section describes in words are made here with Python, to exactly
# the text the section prints: the top of config/settings.py, DATABASES and
# CELERY_BROKER_URL in it, the lines of agenda-api's app/security.py and
# migrations/env.py that read the settings, and the URL taken out of
# alembic.ini. The secrets, the passwords and the tokens are generated by the
# commands shown, differ on every run, and are printed only where a section
# says they are. The development server and agenda-api run in the background,
# where a student runs each in a terminal of its own.
#
# Recorded on Ubuntu 24.04 under systemd-nspawn, TZ=America/Sao_Paulo.
source "$(dirname "$0")/../../capture.sh"

lab reset 15
asroot 'systemctl enable --now postgresql'
at '~/agenda'

block environ
run "uv run python -c \"import os; print(os.environ.get('DJANGO_DEBUG'))\""
run "DJANGO_DEBUG=1 uv run python -c \"import os; print(os.environ.get('DJANGO_DEBUG'))\""

block settings
put /tmp/top.py <<'PY'
import re
p = 'config/settings.py'
s = open(p).read()
top = '''import os
from pathlib import Path

# Build paths inside the project like this: BASE_DIR / 'subdir'.
BASE_DIR = Path(__file__).resolve().parent.parent

SECRET_KEY = os.environ["DJANGO_SECRET_KEY"]
DEBUG = os.environ.get("DJANGO_DEBUG") == "1"
ALLOWED_HOSTS = [host for host in os.environ.get("DJANGO_ALLOWED_HOSTS", "").split(",") if host]
'''
s = re.sub(r"from pathlib import Path\n.*?ALLOWED_HOSTS = \[\]\n", top, s, count=1, flags=re.S)
dbs = '''DATABASES = {
    'default': {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': os.environ.get('DATABASE_NAME', 'agenda'),
        'USER': os.environ.get('DATABASE_USER', ''),
        'PASSWORD': os.environ.get('DATABASE_PASSWORD', ''),
        'HOST': os.environ.get('DATABASE_HOST', ''),
    }
}
'''
s = re.sub(r"DATABASES = \{.*?\n\}\n", dbs, s, count=1, flags=re.S)
s = s.replace('CELERY_BROKER_URL = "redis://127.0.0.1:6379/0"', 'CELERY_BROKER_URL = os.environ.get("CELERY_BROKER_URL", "redis://127.0.0.1:6379/0")', 1)
open(p, 'w').write(s)
PY
quiet 'python3 /tmp/top.py'
run "grep -n 'os.environ' config/settings.py"
run 'uv run python manage.py check 2>&1 | tail -1'
run "printf 'DJANGO_SECRET_KEY=%s\nDJANGO_DEBUG=1\n' \"\$(python3 -c 'import secrets; print(secrets.token_urlsafe(50))')\" > .env"
run 'uv run --env-file .env python manage.py check'

block role
run "printf 'DATABASE_USER=agenda_app\nDATABASE_PASSWORD=%s\nDATABASE_HOST=localhost\n' \"\$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')\" >> .env"
run "echo \"create role agenda_app login createdb password :'pw'\" | sudo -u postgres psql -v pw=\"\$(sed -n 's/^DATABASE_PASSWORD=//p' .env)\""
run 'sudo -u postgres psql agenda -c "reassign owned by ana to agenda_app" -c "alter database agenda owner to agenda_app"'
run 'psql -U agenda_app agenda -c "select current_user"'
run "PGPASSWORD=wrong psql -h localhost -U agenda_app agenda -c 'select current_user'"
run 'uv run --env-file .env python manage.py dbshell -- -c "select current_user, inet_server_addr()"'
run 'uv run --env-file .env pytest -q'

block fastapi
at '~/agenda-api'
run 'uv add pydantic-settings'
from pydantic-settings.md app/config.py
run "uv run python -c 'from app.config import settings' 2>&1 | tail -6"
run "printf 'AGENDA_API_SECRET_KEY=%s\nAGENDA_API_DATABASE_URL=postgresql+psycopg://agenda_api_app:%s@localhost/agenda_api\n' \"\$(python3 -c 'import secrets; print(secrets.token_urlsafe(50))')\" \"\$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')\" > .env"
run "echo \"create role agenda_api_app login password :'pw'\" | sudo -u postgres psql -v pw=\"\$(sed -n 's|^AGENDA_API_DATABASE_URL=.*agenda_api_app:\\(.*\\)@.*|\\1|p' .env)\""
run 'sudo -u postgres psql agenda_api -c "reassign owned by ana to agenda_api_app" -c "alter database agenda_api owner to agenda_api_app"'
run "uv run python -c 'from app.config import settings; print(settings)'"
from pydantic-settings.md app/db.py
put /tmp/sec.py <<'PY'
p = 'app/security.py'
s = open(p).read()
s = s.replace('from .db import SessionDep\n', 'from .config import settings\nfrom .db import SessionDep\n', 1)
import re
s = re.sub(r'SECRET_KEY = ".*?"  # lesson 15 moves it out\n', 'SECRET_KEY = settings.secret_key.get_secret_value()\n', s, count=1)
s = s.replace('TOKEN_MINUTES = 30\n', 'TOKEN_MINUTES = settings.token_minutes\n', 1)
open(p, 'w').write(s)
p = 'migrations/env.py'
s = open(p).read()
s = s.replace('from app.models import Base\n\ntarget_metadata = Base.metadata\n',
              'from app.config import settings\nfrom app.models import Base\n\nconfig.set_main_option("sqlalchemy.url", settings.database_url.get_secret_value())\ntarget_metadata = Base.metadata\n', 1)
open(p, 'w').write(s)
p = 'alembic.ini'
s = open(p).read()
s = s.replace('sqlalchemy.url = postgresql+psycopg:///agenda_api\n', '', 1)
open(p, 'w').write(s)
PY
quiet 'python3 /tmp/sec.py'
run "grep -n 'settings' app/security.py migrations/env.py"
run 'grep -c "sqlalchemy.url" alembic.ini'
run 'uv run alembic current 2>&1 | tail -1'
run 'uv run pytest -q'
WAIT=5 serve api 'uv run uvicorn app.main:app --port 8001'
run 'curl -s http://127.0.0.1:8001/me -H "Authorization: Bearer $(cat token.txt)"; echo'
run "curl -s http://127.0.0.1:8001/token -d username=bruno -d password=m4-orchard-copper-17 | python3 -c \"import json, sys; print(json.load(sys.stdin)['access_token'])\" > token.txt"
run 'curl -s http://127.0.0.1:8001/me -H "Authorization: Bearer $(cat token.txt)"; echo'
stop api

block secrets
