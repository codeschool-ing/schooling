#!/usr/bin/env bash
# The terminal sessions quoted in lesson 9 of db-reliability, as a script that
# produces them.
#
# THE SCRIPT IS THE SOURCE AND ITS OUTPUT IS NOT COMMITTED. Every transcript in
# this lesson was copied from running it.
#
#   sudo bash ../../lab.sh up        # once
#   sudo bash captures.sh
#
# It starts from the machine as lesson 5 leaves it, rebuilt quietly: `lab.sh
# base`, the second server 16/restore, pgbackrest.conf as lesson 5 prints it,
# archive-push, the stanza and one full backup in repo1. The new
# pgbackrest.conf is taken out of this lesson's a-second-repository.md, with a
# passphrase generated by the command that section shows in place of its
# placeholder, as the lesson tells the student to do. The backup labels in the
# commands are copied from `info`, as a person would copy them.
#
# /srv/offsite is a directory on the same machine standing in for storage
# somewhere else; the lesson says so.
#
# Recorded on Ubuntu 24.04, PostgreSQL 16.15, pgBackRest 2.50,
# TZ=America/Sao_Paulo.
cd "$(dirname "$0")"
. ../../lab/lib.sh

lab base
lab exec 'sudo pg_createcluster 16 restore --port 5433 >/dev/null && sudo pg_ctlcluster 16 restore start && sudo -u postgres createuser -p 5433 --superuser ana'
extract ../le-5277pqzg/first-restore.md verify.sql | lab exec 'cat > verify.sql'
extract ../le-62bgpm2d/setting-up.md pgbackrest.conf | lab exec 'sudo tee /etc/pgbackrest.conf > /dev/null'
printf "ALTER SYSTEM SET archive_mode = on;\nALTER SYSTEM SET archive_command = 'pgbackrest --stanza=main archive-push %%p';\n" | lab psql shop >/dev/null
lab exec 'sudo pg_ctlcluster 16 main restart && sudo -u postgres pgbackrest --stanza=main stanza-create && sudo -u postgres pgbackrest --stanza=main backup --type=full'

PASS=$(openssl rand -base64 48 | tr -d '\n')
extract a-second-repository.md pgbackrest.conf | sed "s|PASTE-YOUR-PASSPHRASE-HERE|$PASS|" | lab exec 'sudo tee /etc/pgbackrest.conf > /dev/null'

block protect
on 'sudo mkdir -p /srv/offsite/pgbackrest'
on 'sudo chown postgres:postgres /srv/offsite/pgbackrest'
on 'sudo chmod 750 /srv/offsite/pgbackrest'
on 'sudo chown root:postgres /etc/pgbackrest.conf'
on 'sudo chmod 640 /etc/pgbackrest.conf'
on 'ls -l /etc/pgbackrest.conf'

block stanza
on 'sudo -u postgres pgbackrest --stanza=main --log-level-console=info stanza-create'

block backups
on 'sudo -u postgres pgbackrest --stanza=main backup'
on 'sudo -u postgres pgbackrest --stanza=main --repo=2 backup --type=full'
on 'sudo -u postgres pgbackrest --stanza=main info'

L1=$(lab exec "sudo -u postgres pgbackrest --stanza=main --repo=1 info | awk '/full backup:/ {print \$3; exit}'")
L2=$(lab exec "sudo -u postgres pgbackrest --stanza=main --repo=2 info | awk '/full backup:/ {print \$3; exit}'")

block encrypted
on "sudo file /var/lib/pgbackrest/backup/main/$L1/pg_data/PG_VERSION.zst /srv/offsite/pgbackrest/backup/main/$L2/pg_data/PG_VERSION.zst"

block lose
on 'sudo rm -rf /var/lib/pgbackrest/archive /var/lib/pgbackrest/backup'
on 'sudo -u postgres pgbackrest --stanza=main info'
printf "INSERT INTO orders (customer_id, total_cents, placed_at) VALUES (3, 2100, now());\nSELECT pg_switch_wal();\n" | lab psql shop >/dev/null
sleep 3
printf "SELECT archived_count, failed_count, last_failed_wal FROM pg_stat_archiver;\n" | session shop

block restore-repo2
on 'sudo pg_ctlcluster 16 restore stop'
on 'sudo rm -rf /var/lib/postgresql/16/restore'
on 'sudo -u postgres pgbackrest --stanza=main --repo=2 --pg1-path=/var/lib/postgresql/16/restore --archive-mode=off restore'
on 'sudo pg_ctlcluster 16 restore start'
on 'psql -X -A -t shop -f verify.sql > live.txt'
on 'psql -X -A -t -p 5433 shop -f verify.sql > restored.txt'
on 'diff live.txt restored.txt && echo identical'

block rebuild
on 'sudo -u postgres pgbackrest --stanza=main stanza-create'
on 'sudo -u postgres pgbackrest --stanza=main --repo=1 backup --type=full'
sleep 3
printf "SELECT archived_count, failed_count, last_archived_wal, last_failed_wal FROM pg_stat_archiver;\n" | session shop

block wrong-key
on "sudo sed 's/^repo2-cipher-pass=./repo2-cipher-pass=X/' /etc/pgbackrest.conf | sudo tee /tmp/wrong.conf > /dev/null"
on 'sudo chown postgres /tmp/wrong.conf'
on "sudo -u postgres pgbackrest --config=/tmp/wrong.conf --stanza=main --repo=2 info | grep -v 'outside of section'"
on 'sudo rm /tmp/wrong.conf'

block immutable
on 'sudo -u postgres pgbackrest --stanza=main --repo=2 backup --type=full'
on "sudo chattr -R +i /srv/offsite/pgbackrest/backup/main/$L2"
on "sudo lsattr -d /srv/offsite/pgbackrest/backup/main/$L2"
on "sudo rm /srv/offsite/pgbackrest/backup/main/$L2/backup.manifest"
on "sudo -u postgres pgbackrest --stanza=main --repo=2 expire --set=$L2"

block undo
on "sudo chattr -R -i /srv/offsite/pgbackrest/backup/main/$L2"
on "sudo lsattr -d /srv/offsite/pgbackrest/backup/main/$L2"
